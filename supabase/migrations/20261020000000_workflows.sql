begin;

do $$
declare table_name text;
begin
  foreach table_name in array array[
    'workflows', 'workflow_runs', 'workflow_step_runs', 'social_post_plans'
  ] loop
    execute format('create table if not exists public.%I (
      id uuid primary key default gen_random_uuid(),
      company_id uuid not null references public.companies(id) on delete cascade,
      payload jsonb not null,
      created_at timestamptz not null default now(),
      updated_at timestamptz not null default now(),
      constraint %I check (jsonb_typeof(payload) = ''object'')
    )', table_name, table_name || '_payload_object');
    execute format('alter table public.%I add column if not exists office_id uuid generated always as ((payload->>''officeId'')::uuid) stored', table_name);
    execute format('create index if not exists %I on public.%I (company_id, office_id)', table_name || '_office_idx', table_name);
    execute format('drop trigger if exists office_updated on public.%I', table_name);
    execute format('create trigger office_updated before update on public.%I for each row execute function public.office_touch_updated_at()', table_name);
    execute format('alter table public.%I enable row level security', table_name);
    execute format('revoke all on public.%I from anon, authenticated', table_name);
    execute format('grant select, insert, update, delete on public.%I to service_role', table_name);
  end loop;
end;
$$;

alter table public.workflows
  add column if not exists enabled boolean generated always as ((payload->>'enabled')::boolean) stored,
  add column if not exists next_run_at timestamptz generated always as ((payload->>'nextRunAt')::timestamptz) stored;
create index if not exists workflows_due_idx on public.workflows (company_id, next_run_at) where enabled;

alter table public.workflow_runs
  add column if not exists workflow_id uuid generated always as ((payload->>'workflowId')::uuid) stored,
  add column if not exists status text generated always as (payload->>'status') stored;
create index if not exists workflow_runs_workflow_idx on public.workflow_runs (company_id, workflow_id, created_at desc);
create index if not exists workflow_runs_status_idx on public.workflow_runs (company_id, status);

alter table public.workflow_step_runs
  add column if not exists run_id uuid generated always as ((payload->>'runId')::uuid) stored,
  add column if not exists status text generated always as (payload->>'status') stored;
create index if not exists workflow_step_runs_run_idx on public.workflow_step_runs (company_id, run_id);

alter table public.social_post_plans
  add column if not exists platform text generated always as (payload->>'platform') stored,
  add column if not exists status text generated always as (payload->>'status') stored,
  add column if not exists scheduled_at timestamptz generated always as ((payload->>'scheduledAt')::timestamptz) stored;
create index if not exists social_post_plans_due_idx on public.social_post_plans (company_id, scheduled_at) where status in ('approved', 'publishing');
create index if not exists social_post_plans_run_idx on public.social_post_plans (company_id, scheduled_at desc);

comment on table public.workflows is 'Reusable multi-agent flow definitions with an optional daily/cron schedule.';
comment on table public.workflow_runs is 'Snapshotted workflow executions, including approval and revision state.';
comment on table public.workflow_step_runs is 'Per-step agent tasks, reports and approval outcomes for a workflow run.';
comment on table public.social_post_plans is 'Approved posting schedules generated by a workflow social-plan step. Publishing results are real or explicitly failed.';
commit;
